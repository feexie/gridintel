/* ==========================================================
   COMPOSITION ROOT

   The one place that chooses which adapter the application runs
   on. Everything else receives repositories and never names an
   adapter. Server-side only.

   The application currently runs on the synthetic demonstration
   dataset, whose "now" is a fixed demo clock rather than the wall
   clock, so results are the same on every run.
========================================================== */

/**
 * The repositories and the result cache are held once per server PROCESS, not once per
 * module: the server bundles this file into more than one chunk (the routes, and the
 * start-up hook), and each chunk would otherwise build its own dataset and its own cache.
 */
interface ProcessState {
  repositories: GridIntelRepositories | null;
  results: ReturnType<typeof createMemoryCache>;
  /** The mini-grid operator's records and the results computed from them: a set of their own. */
  minigrid: { repositories: GridIntelRepositories | null; spatialRepositories?: GridIntelRepositories; results: ReturnType<typeof createMemoryCache> };
  readiness: Readiness;
}

/**
 * Where the start-up warm-up stands (see warm.ts):
 * - not_started: no warm-up was begun in this process (a build, a test, a script);
 * - warming: the screens are being computed; data routes answer with a "preparing data" page;
 * - ready: the screens are computed;
 * - failed: the warm-up stopped on an error; screens compute on request.
 */
export type Readiness = "not_started" | "warming" | "ready" | "failed";

const globalState = globalThis as typeof globalThis & { __gridintel?: ProcessState };
const state: ProcessState = (globalState.__gridintel ??= {
  repositories: null,
  results: createMemoryCache(),
  minigrid: { repositories: null, results: createMemoryCache() },
  readiness: "not_started",
});

export function getReadiness(): Readiness {
  return state.readiness;
}

export function setReadiness(readiness: Readiness): void {
  state.readiness = readiness;
}

/**
 * True while the warm-up is running. A data route then shows its "preparing data" page and
 * calculates nothing, so the request is answered at once instead of waiting for the warm-up.
 * In any other state the route calculates as usual.
 */
export function isPreparing(): boolean {
  return state.readiness === "warming";
}

/**
 * True when the running adapter's records cannot change and its clock does not move, so that
 * every screen is the same on every request for as long as the build is. The synthetic
 * demonstration adapter is such an adapter: its dataset is generated by code and "now" is the
 * fixed demo clock. An adapter over a database, an API or telemetry must answer false.
 *
 * When it is true, the network screens are rendered when the application is built and no
 * warm-up runs (ADR 0012). When it is false, every screen is rendered on request from the
 * result cache, behind the warm-up and the preparing page.
 *
 * GRIDINTEL_RENDER=request makes this answer false on the demonstration adapter, at build time
 * and at run time alike. It exists so that the request path stays built and tested while the
 * only adapter is a fixed one; nothing else reads it.
 */
const ADAPTER_DATASET_IS_FIXED = true;

export function datasetIsFixed(): boolean {
  // A tenant deployment renders every screen for the person who asks (ADR 0020).
  return ADAPTER_DATASET_IS_FIXED && process.env.GRIDINTEL_RENDER !== "request" && deploymentMode() !== "tenant";
}

/* ==========================================================
   THE GATE (Phase 8A, ADR 0020)

   Every read of a sector's records passes here first. In a tenant
   deployment it asks, of the viewer built from records (identity.ts):

   1. does their organization hold this sector's records? The grant
      is cut to the organization's sectors, so a person of the
      mini-grid operator never holds "utility", whatever is asked;
   2. does their grant open the screen being asked for? The proxy
      writes the address into the request (PATH_HEADER); a request
      without it opens nothing.

   Either answer "no" is "not found": the records of another
   organization are not said to exist. The proxy's refusal page
   with 403 is the first check (ADR 0018); this is the one that
   holds where the data is read.

   The public demonstration's viewer holds everything and is asked
   nothing, so its screens can still be built ahead of time. The
   start-up warm-up computes each sector's screens into that
   sector's own cache for no one (mode.ts, `asSystem`).
========================================================== */

export type DatasetSector = "utility" | "minigrid";

export async function gate(sector: DatasetSector): Promise<void> {
  if (deploymentMode() === "demo" || isSystemWork()) return;
  const viewer = await getViewer();
  // Next's request functions are loaded here, on a tenant deployment's path only.
  const { headers } = await import("next/headers");
  if (!admitsRead(viewer.screens, sector, (await headers()).get(PATH_HEADER))) await refuse();
}

/** Answers the request "not found": what a viewer who may not read the records is told. */
export async function refuse(): Promise<never> {
  const { notFound } = await import("next/navigation");
  return notFound();
}

/**
 * The synthetic demonstration adapter, with Nigeria's states and LGAs from geoBoundaries added
 * to its areas. The boundaries are real reference geography and the network is synthetic; the
 * spatial services never relate the two (ADR 0014).
 */
export function getRepositories(): GridIntelRepositories {
  // On the public demonstration the mini-grid operator's sites are drawn beside the utility's
  // network, so their sources are listed with the utility's. A tenant's lists hold its own only.
  state.repositories ??= deploymentMode() === "demo" ? withDataSources(withGeoBoundaries(createDemoRepositories()), MINIGRID_DATA_SOURCES) : withGeoBoundaries(createDemoRepositories());
  return state.repositories;
}

/**
 * The same repositories, with more data sources on their list. The list of data sources is the
 * platform's: a record shown beside the utility's (a mini-grid site on the shared map) names a
 * source that must be found there, so that it is known to be synthetic. No record is added.
 */
function withDataSources(repos: GridIntelRepositories, sources: readonly DataSource[]): GridIntelRepositories {
  return { ...repos, sources: { listDataSources: async () => [...(await repos.sources.listDataSources()), ...sources] } };
}

/* ==========================================================
   THE MINI-GRID OPERATOR'S RECORDS

   A mini-grid operator is another organization than the
   distribution utility, and its records are another set of
   repositories with a result cache of their own (rule 3 below).
   The utility's screens never read them, and nothing of the
   utility's is mixed into a site's figures (ADR 0015).

   Today both sets are synthetic demonstration data on the same
   fixed clock.
========================================================== */

export function getMinigridRepositories(): GridIntelRepositories {
  state.minigrid.repositories ??= createMinigridDemoRepositories();
  return state.minigrid.repositories;
}

function minigridRuntime(repos: GridIntelRepositories): OperationsRuntime {
  const clock = getClock();
  return { repos, now: clock.now, period: clock.reportingPeriod, caveats: { tariffs: getDataNotice()?.caveats.tariffs }, cache: state.minigrid.results };
}

/** What the mini-grid read models are given, past the gate: the operator's repositories, the clock and their own cache. */
export async function getMinigridRuntime(): Promise<OperationsRuntime> {
  await gate("minigrid");
  return minigridRuntime(getMinigridRepositories());
}

/**
 * The same, with the states and LGAs added to its areas: the spatial runtime of an organization
 * that holds the mini-grid sector and not the utility's (spatial.ts).
 */
export async function getMinigridSpatialRuntime(): Promise<OperationsRuntime> {
  await gate("minigrid");
  state.minigrid.spatialRepositories ??= withGeoBoundaries(getMinigridRepositories());
  return minigridRuntime(state.minigrid.spatialRepositories);
}

export interface RuntimeClock {
  /** The instant "now" means for as-of queries and for `computedAt`. */
  now: IsoTimestamp;
  /** The reporting period shown by default. */
  reportingPeriod: Period;
}

/** What must be said about the data the application is running on; null for real data. */
export interface DataNotice {
  label: string;
  summary: string;
  caveats: { feederLoading?: string; tariffs?: string };
}

export function getDataNotice(): DataNotice | null {
  return DEMO_NOTICE;
}

export function getClock(): RuntimeClock {
  return { now: DEMO_CLOCK, reportingPeriod: DEMO_PERIOD };
}

/** What the bar above every screen shows: what the data is, the reporting period and the as-of time. */
export function getDataContext(): { notice: { label: string; summary: string } | null; period: Period; asOf: IsoTimestamp } {
  const notice = getDataNotice();
  const clock = getClock();
  return { notice: notice === null ? null : { label: notice.label, summary: notice.summary }, period: clock.reportingPeriod, asOf: clock.now };
}

